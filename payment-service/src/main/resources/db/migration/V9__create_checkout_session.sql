CREATE TABLE checkout_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_checkout_session_payment
        FOREIGN KEY (payment_id)
        REFERENCES payment(id),
    CONSTRAINT uk_checkout_session_token_hash
        UNIQUE (token_hash),
    CONSTRAINT chk_checkout_session_token_hash_length
        CHECK (length(token_hash) = 64)
);

CREATE INDEX idx_checkout_session_payment_id
    ON checkout_session(payment_id);
